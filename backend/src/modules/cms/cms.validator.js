import { z } from "zod";

export const sectionUpsertSchema = z.object({
  locale: z.enum(["en", "bn"]).default("en"),
  data: z.union([z.record(z.any()), z.string()]).optional().default({}),
  dataEn: z.union([z.record(z.any()), z.string()]).optional(),
  dataBn: z.union([z.record(z.any()), z.string()]).optional(),
  seo_title: z.string().max(70, "SEO Title cannot exceed 70 characters").optional().nullable(),
  seoTitleEn: z.string().max(70, "SEO Title cannot exceed 70 characters").optional().nullable(),
  seoTitleBn: z.string().max(70, "SEO Title cannot exceed 70 characters").optional().nullable(),
  seo_description: z.string().max(170, "SEO Description cannot exceed 170 characters").optional().nullable(),
  seoDescriptionEn: z.string().max(170, "SEO Description cannot exceed 170 characters").optional().nullable(),
  seoDescriptionBn: z.string().max(170, "SEO Description cannot exceed 170 characters").optional().nullable(),
  status: z.enum(["draft", "published", "archived"]).optional().default("published"),
});

export const testimonialCreateSchema = z.object({
  locale: z.enum(["en", "bn"]).default("en"),
  student_name: z.string().trim().min(1, "Student name is required").optional(),
  studentName: z.string().trim().min(1).optional(),
  studentNameEn: z.string().trim().min(1).optional(),
  studentNameBn: z.string().optional().nullable(),
  designation: z.string().optional().nullable(),
  designationEn: z.string().optional().nullable(),
  designationBn: z.string().optional().nullable(),
  message: z.string().trim().min(1, "Message is required").optional(),
  messageEn: z.string().trim().min(1).optional(),
  messageBn: z.string().optional().nullable(),
  image_url: z.string().optional().nullable(),
  imageUrl: z.string().optional().nullable(),
  video_url: z.string().optional().nullable(),
  videoUrl: z.string().optional().nullable(),
  rating: z.number().int().min(1).max(5).optional().nullable(),
  sort_order: z.number().int().optional().default(0),
  sortOrder: z.number().int().optional(),
  is_active: z.boolean().optional().default(true),
  isActive: z.boolean().optional(),
}).refine((data) => data.student_name || data.studentName || data.studentNameEn || data.studentNameBn, {
  message: "Student name is required",
  path: ["studentNameEn"],
}).refine((data) => data.message || data.messageEn || data.messageBn, {
  message: "Message is required",
  path: ["messageEn"],
});

